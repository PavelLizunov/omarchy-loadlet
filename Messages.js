function text(key, values) {
  var localeName = Qt.locale().name.toLowerCase()
  var lang = localeName.split("_")[0].split("-")[0]
  var catalog = strings[lang] || strings["en"]
  var template = catalog[key] || strings["en"][key] || key
  return template.replace(/\{(\w+)\}/g, function(token, name) {
    return values && values[name] !== undefined ? String(values[name]) : token
  })
}
